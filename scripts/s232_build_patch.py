def P(*p):
    return os.path.join(ROOT, *p)


def read(path):
    with io.open(path, "r", encoding="utf-8") as f:
        return f.read().split("\n")


def write(path, lines):
    with io.open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def replace_block(src_lines, start_prefix, must_contain, new_block, path):
    """استبدال سطر واحد يبدأ بـstart_prefix ويحوي must_contain بكتلة."""
    si = [i for i, l in enumerate(src_lines)
          if l.startswith(start_prefix) and must_contain in l]
    if len(si) != 1:
        sys.exit(f"ERR: مرساة «{start_prefix[:40]}…» + «{must_contain[:30]}» "
                 f"بـ{path}: {len(si)}")
    src_lines[si[0]:si[0] + 1] = new_block
    return True


