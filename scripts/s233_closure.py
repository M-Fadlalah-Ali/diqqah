"""س233 — الإغلاق التوثيقي: أرقام الجولات والبناء بمدخل السجل، وصفوف
خريطة الحالة، وإدخال سجل الإصدارات. صادق بحالته: الجولتان خضراوان
كاملتان من أول مرة والبناء b85 منطلق عند كتابة الختام — فخضرته
وأثرتاه يوثقان عند اكتماله بجلسة تالية إن ضاق الوقت."""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKLOG = os.path.join(ROOT, "worklog.md")
STATEMAP = os.path.join(ROOT, "docs", "manuals", "01-خريطة-الحالة.md")


def _read(p):
    with io.open(p, encoding="utf-8") as f:
        return f.read()


def _write(p, t):
    with io.open(p, "w", encoding="utf-8") as f:
        f.write(t)


# ١) مدخل السجل: إكمال (7) الجولة والبناء و(8) المعلق
WL_OLD = """— والحكم بجولة الاستطلاع بفرع probe-s233 ثم دفع main ثم dispatch البناء فb85.
"""
WL_NEW = """— والحكم بجولة الاستطلاع بفرع probe-s233 ثم دفع main ثم dispatch البناء فb85.

**(7) الجولة الحاكمة والبناء b85**: الاستطلاع بفرع probe-s233 بworkflow_dispatch (عرف س227) — **الجولة 46148781531 خضراء كاملة بالمهام الخمس من أول جولة** (بوابة الأسرار وحارس النصوص بخط أساسه الجديد والمجال والتخزين والواجهة) ثم دفع main (وحذف فرع الاستطلاع بعيداً) ف**جولة main 46149263864 خضراء كاملة** — ثم dispatch بناء الحزم رجع 204 فانطلق **التشغيل b85 (run 46149704042) على رأس الشجرة المحكومة (882dc84) بكلمة الخطة «الجودة والبناء → 0.285.0+85»** — والإغلاق يكتب والبناء يجري: خضرته وأثرتاه (القياس البايتي والمسبار ⑤ بأداة الحارس والقراءة البايتية لversionCode 2085) يوثقان عند اكتماله بجلسة اللحاق — وجولة CI التوثيقية لهذا الإغلاق تحكم الدفعة.

**(8) المعلق على المالك**: (أ) تثبيت b85 (v.0.285) فوق 0.284 بلا حذف (2085 فوق 2084 بخاتم واحد) فور خضرة بنائه. (ب) نقطة التفتيش: عرض نتيجة المرحلة أ قبل الشروع بالمرحلة ب (سجل الفواتير D-234) — وفيها موضعان بيد المالك: بنية الأقسام الستة المعاد بناؤها (من مخطط D-218 القائم بشطر قسمه المزدوج) وصفوف التقارير ISO (الصيغة الطويلة للمطبوعات والمنتقي دون الصفوف). (ج) موضع د10 البنوك ود13 من الخارطة الجديدة (تأخرا خلف المراحل بكلمة المالك). (د) تدوير الرمز بعد الجلسة (D-173). — بيد المالك.
"""

# ٢) خريطة الحالة: الترويسة إلى حالتها المنجزة الصادقة
SM_OLD = "ثم دفع main ثم dispatch البناء فb85 (versionCode 2085)"
SM_NEW = ("والجولتان خضراوان كاملتان من أول مرة (استطلاع 46148781531 فmain 46149263864) "
          "وdispatch البناء b85 (run 46149704042) بكلمة الخطة — خضرته وأثرتاه "
          "يوثقان عند اكتماله بجلسة اللحاق، والترقيم 0.285.0+85 وversionCode 2085 "
          "بالاصطفاح الرباعي")


def main():
    s = _read(WORKLOG)
    if "(7) الجولة الحاكمة والبناء b85" not in s:
        assert WL_OLD in s, "ذيل مدخل س233 غير موجود"
        _write(WORKLOG, s.replace(WL_OLD, WL_NEW, 1))
        print("worklog (7)+(8): أُكملا")
    else:
        print("worklog: مكتمل مسبقاً")

    s = _read(STATEMAP)
    if "46149704042" not in s:
        assert SM_OLD in s, "ترويسة الخريطة بصيغتها القديمة غير موجودة"
        _write(STATEMAP, s.replace(SM_OLD, SM_NEW, 1))
        print("خريطة الحالة: حُدثت")
    else:
        print("خريطة الحالة: محدثة مسبقاً")


if __name__ == "__main__":
    main()
