def read(path):
    with io.open(path, 'r', encoding='utf-8') as f:
        return f.read()


def write(path, text):
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(text)


def replace_once(text, old, new, what):
    assert text.count(old) == 1, f'المرساة غير فريدة ({text.count(old)}): {what}'
    return text.replace(old, new)


def replace_row(text, row_prefix, new_row, what):
    """استبدال صف جدول كامل ببادئته المعروفة."""
    lines = text.split('\n')
    hits = [i for i, ln in enumerate(lines) if ln.startswith(row_prefix)]
    assert len(hits) == 1, f'الصف غير فريد ({len(hits)}): {what}'
    lines[hits[0]] = new_row
    return '\n'.join(lines)


