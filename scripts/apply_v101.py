errors = []

def load(name):
    with io.open(os.path.join(BASE, name), "r", encoding="utf-8") as f:
        return f.read().split("\n")

def save(name, lines):
    with io.open(os.path.join(BASE, name), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

def find_line(lines, predicate, desc, expect=1):
    idxs = [i for i, l in enumerate(lines) if predicate(l)]
    if len(idxs) != expect:
        errors.append("[{}] anchor {}: found {} expected {}".format(desc_name(desc), desc, len(idxs), expect))
        return None
    return idxs[0]

def desc_name(d):
    return d.split("::")[0] if "::" in d else d

def sub(lines, old, new, name, count=1):
    joined = "\n".join(lines)
    n = joined.count(old)
    if n != count:
        errors.append("[{}] sub '{}...': {} occurrences, expected {}".format(name, old[:40], n, count))
        return lines
    return ("\n".join(lines)).replace(old, new).split("\n")

def line_replace(lines, anchor, new_line, name, contains=True):
    pred = (lambda l: anchor in l) if contains else (lambda l: l.startswith(anchor))
    i = find_line(lines, pred, name)
    if i is None:
        return lines
    lines[i] = new_line
    return lines

def insert_after(lines, anchor, block_lines, name, startswith=True):
    pred = (lambda l: l.startswith(anchor)) if startswith else (lambda l: anchor in l)
    i = find_line(lines, pred, name)
    if i is None:
        return lines
    return lines[:i+1] + block_lines + lines[i+1:]

def set_header(lines, version_line, name):
    i = find_line(lines, lambda l: l.startswith("| الإصدار |"), name)
    if i is not None:
        lines[i] = version_line
    j = find_line(lines, lambda l: l.startswith("| التاريخ |"), name)
    if j is not None:
        lines[j] = "| التاريخ | {} |".format(DATE_NEW)
    return lines

