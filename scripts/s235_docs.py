def add_section76():
    t = _read(PLAN)
    if "## 76. قرارا المالك" in t:
        print("09 §76: موجود مسبقاً — تُخطى")
        return
    if not t.endswith("\n"):
        t += "\n"
    _write(PLAN, t + SECTION76)
    print("09 §76: أُضيف (D-238 وD-239)")


def add_worklog():
    t = _read(WORKLOG)
    if "## س235 —" in t:
        print("worklog س235: موجود مسبقاً — تُخطى")
        return
    if not t.endswith("\n"):
        t += "\n"
    _write(WORKLOG, t + WORKLOG_ENTRY)
    print("worklog س235: أُضيف")


def update_statemap():
    t = _read(STATEMAP)
    if "بعد س235" in t:
        print("خريطة الحالة: محدثة مسبقاً — تُتخطى")
        return
    m = re.search(r"\*\*آخر تحديث:\*\*.*$", t, re.M)
    assert m
    new_head = ("**آخر تحديث:** 2026-11-28 — بعد س235 (توحيد النمط الفوري على الشاشات "
                "بقرارَي المالك D-238 القصير ISO بصفوف التقارير وD-239 التوحيد: شريط "
                "المدى الفوري الموحد DiqqahInstantRangeBar بسجل الفواتير والتقارير "
                "والسندات، والميزانية بحقلها الأحادي الفوري، وحذف زر العرض والرقائق "
                "القديمة) — والحكم بجولة الاستطلاع بفرع probe-s235 ثم دفع main ثم "
                "dispatch البناء فb87 (versionCode 2087)")
    t = t[:m.start()] + new_head + t[m.end():]
    _write(STATEMAP, t)
    print("خريطة الحالة (الترويسة): حُدثت")


def add_changelog():
    t = _read(CHANGELOG)
    if "## v.0.287" in t:
        print("CHANGELOG v.0.287: موجود مسبقاً — تُتخطى")
        return
    anchor = "## v.0.286"
    assert anchor in t
    _write(CHANGELOG, t.replace(anchor, CHANGELOG_ENTRY.strip() + "\n\n" + anchor, 1))
    print("CHANGELOG v.0.287: أُضيف")


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("section", "all"):
        add_section76()
    if what in ("batch", "all"):
        add_worklog()
        update_statemap()
    if what in ("changelog", "all"):
        add_changelog()
