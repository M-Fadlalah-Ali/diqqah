def add_section_75():
    text = _read(PLAN)
    if "## 75. قرار المالك بتأجيل د13" in text:
        print("09 §75: موجود مسبقاً — تُخطى")
        return
    if not text.endswith("\n"):
        text += "\n"
    text += SECTION75
    _write(PLAN, text)
    print("09 §75: أُضيف (D-237 تأجيل د13)")


def add_worklog():
    text = _read(WORKLOG)
    if "## س234 —" in text:
        print("worklog س234: موجود مسبقاً — تُخطى")
        return
    if not text.endswith("\n"):
        text += "\n"
    text += WORKLOG_ENTRY
    _write(WORKLOG, text)
    print("worklog س234: أُضيف")


def update_statemap():
    text = _read(STATEMAP)
    if "بعد س234" in text:
        print("خريطة الحالة: محدثة مسبقاً — تُتخطى")
        return
    m = re.search(r"\*\*آخر تحديث:\*\*.*$", text, re.M)
    assert m is not None, "ترويسة الخريطة غير موجودة"
    new_head = ("**آخر تحديث:** 2026-11-28 — بعد س234 (المرحلة ب من خارطة الطريق الخماسية: "
                "سجل الفواتير بالأزرار الثلاثة لكل سجل وإلغاء القائمة السياقية الموروثة، "
                "وأزرار التاريخ الخمسة بسطرها الصغير الفعلي بالأسماء المختارة وتلوين المختار "
                "والتمرير الأفقي عند الضيق، والفلاتر الثلاثة بسطر بالتطبيق الفوري والديبونس "
                "القصير ومسح الفلاتر) بأمر المالك «تابع بتنفيذ المرحلة ب» — وتأجيل د13 موثق "
                "بقرار D-237 (09 §75) بقاعدة التذكير عند السؤال وبنقاط التفتيش — والحكم بجولة "
                "الاستطلاع بفرع probe-s234 ثم دفع main ثم dispatch البناء فb86 (versionCode 2086)")
    text = text[:m.start()] + new_head + text[m.end():]
    _write(STATEMAP, text)
    print("خريطة الحالة (الترويسة): حُدثت")


def add_changelog():
    text = _read(CHANGELOG)
    if "## v.0.286" in text:
        print("CHANGELOG v.0.286: موجود مسبقاً — تُتخطى")
        return
    anchor = "## v.0.285"
    assert anchor in text, "إدخال v.0.285 غير موجود"
    text = text.replace(anchor, CHANGELOG_ENTRY.strip() + "\n\n" + anchor, 1)
    _write(CHANGELOG, text)
    print("CHANGELOG v.0.286: أُضيف")


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("section75", "all"):
        add_section_75()
    if what in ("batch", "worklog", "all"):
        add_worklog()
    if what in ("batch", "statemap", "all"):
        update_statemap()
    if what in ("changelog", "all"):
        add_changelog()
