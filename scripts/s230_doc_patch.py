def P(*p):
    return os.path.join(ROOT, *p)


def read(path):
    with io.open(path, 'r', encoding='utf-8') as f:
        return f.read().split('\n')


def write(path, lines):
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


def replace_row(lines, prefix, new_row, path):
    hits = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    if len(hits) != 1:
        sys.exit(f'ERR: مرساة «{prefix}» بـ{path}: {len(hits)} إصابة')
    if lines[hits[0]] == new_row:
        return False
    lines[hits[0]] = new_row
    return True


def insert_row_after(lines, prefix, new_row, path):
    hits = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    if len(hits) != 1:
        sys.exit(f'ERR: مرساة «{prefix}» بـ{path}: {len(hits)} إصابة')
    at = hits[0] + 1
    if at < len(lines) and lines[at] == new_row:
        return False
    lines.insert(at, new_row)
    return True


