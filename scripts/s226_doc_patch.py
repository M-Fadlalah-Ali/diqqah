    anchor = "| س225 | 2026-11-26 —"
    assert src.count(anchor) == 1, f"مرساة صف س225 ليست واحداً: {src.count(anchor)}"
    head, rest = src.split(anchor, 1)
    row_line, tail = rest.split("\n", 1)
    src = head + anchor + row_line + "\n" + ROW_226 + "\n" + tail
    src = src.rstrip("\n") + "\n" + ENTRY_226
