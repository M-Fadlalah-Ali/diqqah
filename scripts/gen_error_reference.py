# -*- coding: utf-8 -*-
"""مولّد مرجع الأخطاء 08 من سلطة الترقيم error_codes.dart — توليد آلي فلا تخالف حرفاً.
(استعادة الأداة الموثقة س107 — ضاعت بتدوير الصندوق، وأعيد بناءها بجلسة التنظيف المفقودة وأعيد تشغيلها س181)."""
import re

SRC = '/home/z/my-project/diqqah/packages/domain/lib/src/error_codes.dart'
OUT = '/home/z/my-project/diqqah/docs/manuals/08-مرجع-الأخطاء.md'

src = open(SRC, encoding='utf-8').read()

entries = []
for m in re.finditer(
        r"DiqqahErrorCode\(\s*'(DQ-\d{4})'\s*,\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'\s*\)",
        src):
    entries.append((m.group(1), m.group(2), m.group(3)))
unclassified = re.search(
    r"diqqahUnclassifiedError\s*=\s*\n?\s*DiqqahErrorCode\(\s*'(DQ-\d{4})'\s*,\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'\s*\)",
    src)
if unclassified:
    entries.append((unclassified.group(1), unclassified.group(2), unclassified.group(3)))

by_code = {}
for code, title, guidance in entries:
    by_code[code] = (title, guidance)

SECTIONS = [
    ('01', 'حواجز الدفتر والقيود — عند الترحيل أو العبث بقيد مرحّل',
     'رسائل المحرك عند بناء القيود أو مسّ القيود المرحّلة: التوازن والحد الأدنى للأسطر وتجميد المرحّل.'),
    ('02', 'حواجز المخزون والفواتير — عند البيع والشراء والمردودات',
     'رسائل منع السالب المخزني وتجميد الفاتورة المرحّلة وأسطرها.'),
    ('03', 'حواجز الصندوق والسندات — عند القبض والصرف والمطابقة',
     'رسائل منع السالب الموحّد للصندوق وتجميد السندات والمطابقات والتحويل والتسوية.'),
    ('04', 'حواجز التحويل والجرد — عند نقل بضاعة وعدّها',
     'رسائل تجميد مستندات التحويل وجلسات الجرد المرحّلة.'),
    ('05', 'حواجز الإذنين والتجميع وأسعار الصرف',
     'رسائل تجميد إذني الصرف والاستلام ومستندات التجميع وأسعار الصرف المحفوظة.'),
    ('06', 'حاجز الإقفال السنوي — عند العمل داخل فترة مقفلة',
     'رسالة واحدة تحرس كل مستندات الفترة المقفلة إدراجاً وترحيلاً.'),
    ('07', 'طلبات البيع والشراء — حواجز طبقة الأوامر',
     'حواجز جداول الطلبات وآلة حالتها المحروسة (س121 — 07 §3.2: طبقة تشغيلية فوق الفاتورة دون تغيير القلب المحاسبي).'),
    ('10', 'فحوص المجال النقي — التحقق المحاسبي قبل الكتابة',
     'استثناءات الفحص التفصيلي التي تحمل تفصيل رفضٍ معها (كمية سالبة أو فاتورة ناقصة البيانات ونحوها).'),
    ('11', 'البنية والتخزين — المخطط والنسخ الاحتياطي',
     'رسائل فتح القاعدة واستعادتها وتجميد معاملات التعبئة وخدام سجلي الأحداث والأخطاء.'),
]

def table(codes):
    rows = ['| الرمز | الخطأ | ماذا تفعل |', '|---|---|---|']
    for c in codes:
        t, g = by_code[c]
        rows.append(f'| `{c}` | {t} | {g} |')
    return '\n'.join(rows)

out = []
out.append('# مرجع الأخطاء — رموز DQ-xxxx')
out.append('')
out.append('**أُنشئ:** 2026-11-07 (س107 — دفعة «أساس الأخطاء» بكلمة المالك المعتمدة في خريطة الحالة §٢-5). '
           '**جُدِّد:** 2026-11-20 (س181 — إعادة تأسيس تنظيف الرموز وأصله الجلسة المفقودة: تسجيل DQ-1025/1026 وDQ-1119..1122 و1123/1124، '
           'والرسائل المرئية برمزها حصراً بعد نزع الإحالات الداخلية). '
           '**المصدر:** سجل الترقيم في البرنامج ذاته (`error_codes.dart`) — هذا الملف توليد آلي منه فلا يخالفه حرفاً.')
out.append('')
out.append('## كيف تقرأ الخطأ؟')
out.append('')
out.append('كل رسالة رفض تظهر في البرنامج تحمل في آخرها **رمزاً ثابتاً** بين قوسين، مثل:')
out.append('')
out.append('> «القيد المرحّل لا يعدل — التصحيح بقيد عكس **(DQ-0103)**»')
out.append('')
out.append('ابحث بالرمز في هذا المرجع فيعرفك: ما معناه، وماذا تفعل. والرمز **لا يتغير أبداً** — فما تقرأه اليوم تقرأه في كل النسخ القادمة. '
           'وإن ظهر خطأ برمز `DQ-0999` (غير مصنف) فشاركه من **الإعدادات ← التشخيص ومرجع الأخطاء ← مشاركة التشخيص** ليُرقَّم في دفعة قادمة.')
out.append('')
out.append('وشاشة «التشخيص ومرجع الأخطاء» (بالإعدادات، نهاية القائمة) تعرض: هوية نافذتك (الإصدار ورقم المخطط ومعرف الجهاز)، '
           'وآخر ما سُجل من أخطاء على جهازك، وهذا المرجع كاملاً — فزر «مشاركة التشخيص» يجمعها نصاً واحداً تبثه كما هو.')
out.append('')

for prefix, header, desc in SECTIONS:
    codes = sorted(c for c in by_code if c.startswith('DQ-' + prefix))
    if not codes:
        continue
    out.append(f'## {header}')
    out.append('')
    out.append(desc)
    out.append('')
    out.append(table(codes))
    out.append('')

# الفاصلة الآمنة
uc = by_code.get('DQ-0999')
if uc:
    out.append('## DQ-0999 — الفاصلة الآمنة')
    out.append('')
    out.append(table(['DQ-0999']))
    out.append('')

out.append('## حدود هذا المرجع (صدق الدفعة)')
out.append('')
out.append('1. الرموز أعلاه تغطي حواجز قاعدة البيانات (DQ-01xx..07xx) وفحوص المجال (10xx) والبنية (11xx) — وهي **كل** رسائل الرفض التي يولدها المحرك بنصها المرقّم منذ ترحيلة v24، وبترحيلة v31 أعيدت نصوص الحواجز كلها مرقّمةً منزَّعةَ الإحالات الداخلية على القواعد القائمة والجديدة معاً.')
out.append('2. رسائل الطباعة والتصدير (أخطاء ملفات ونظام التشغيل) تظهر بنصها الحقيقي وقد لا تحمل رمزاً بعد — فالطبقة تتوسع بدفعات قادمة وتلك نصوص بيئة لا قرارات برنامج.')
out.append('3. أخطاء الافتتاح قبل فتح القاعدة تُعرض وتُشارك من شاشة خطأ الافتتاح (D-197) نصاً — لا يمكن تسجيلها بسجلّ قاعدةٍ غير مفتوحة، وهذا حدٌّ بنيوي موثق لا قصور.')
out.append('4. سجل الأخطاء على جهازك محلي append-only: لا يُرفع لأي مكان ولا يُحذف من البرنامج.')
out.append('')

text = '\n'.join(out)
open(OUT, 'w', encoding='utf-8').write(text)
n = len([c for c in by_code if c != 'DQ-0999'])
print(f'OK — {n} رمزاً + الفاصلة الآمنة، الأقسام {len(SECTIONS)}')
missing = [c for c, t, g in entries if not t or not g]
print('بلا عنوان/وجاهة:', missing or 'لا شيء')
