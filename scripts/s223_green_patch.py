def patch():
    lines = io.open(MAP_PATH, encoding="utf-8").read().splitlines()
    out = []
    header_done = branch_done = stage_done = row_done = False
    for line in lines:
        if line.startswith(HEADER_PREFIX) and not header_done:
            out.append(HEADER_NEW)
            header_done = True
        elif line.startswith(BRANCH_PREFIX) and not branch_done:
            out.append(BRANCH_NEW)
            branch_done = True
        elif line.startswith(STAGE_PREFIX) and not stage_done:
            out.append(STAGE_NEW)
            stage_done = True
        elif line.startswith(ROW_223_PREFIX) and not row_done:
            out.append(ROW_223_NEW)
            row_done = True
        else:
            out.append(line)
    assert all([header_done, branch_done, stage_done, row_done]), \
        f"مراسي الخضرة ناقصة: {header_done} {branch_done} {stage_done} " \
        f"{row_done}"
    io.open(MAP_PATH, "w", encoding="utf-8").write("\n".join(out) + "\n")


def verify():
    m = io.open(MAP_PATH, encoding="utf-8").read()
    ok = True
    for needle in ("#451 خضراء كاملة", "45609199664", "بعد تصويب اختباري",
                   "فد5 منفَّذة كاملةً"):
        if needle not in m:
            print(f"مفقود: {needle!r}")
            ok = False
    print("CLEAN" if ok else "FAIL")


if __name__ == "__main__":
    patch()
    verify()
