def patch_map():
    src = io.open(MAP_PATH, encoding="utf-8").read()
    lines = src.splitlines()
    out = []
    header_done = branch_done = stage_done = release_done = row_done = False
    for line in lines:
        if line.startswith("**آخر تحديث:**") and not header_done:
            out.append(HEADER_NEW)
            header_done = True
        elif line.startswith("| الفرع |") and not branch_done:
            out.append(BRANCH_NEW)
            branch_done = True
        elif line.startswith("| المرحلة النشطة |") and not stage_done:
            out.append(STAGE_NEW)
            stage_done = True
        elif line.startswith("| آخر إصدار |") and not release_done:
            out.append(RELEASE_NEW)
            release_done = True
        elif (line.startswith("| س220 | 2026-11-25 | إغلاق بناء 0.274")
              and not row_done):
            out.append(line)
            out.append(ROW_221)
            row_done = True
        else:
            out.append(line)
    assert all([header_done, branch_done, stage_done, release_done, row_done]), \
        f"مراسي الخريطة ناقصة: {header_done} {branch_done} {stage_done} " \
        f"{release_done} {row_done}"
    io.open(MAP_PATH, "w", encoding="utf-8").write("\n".join(out) + "\n")


def patch_plan():
    src = io.open(PLAN_PATH, encoding="utf-8").read()
    assert "## 61." not in src, "قسم §61 موجود سلفاً"
    src = src.rstrip("\n") + "\n" + SECTION_61
    io.open(PLAN_PATH, "w", encoding="utf-8").write(src)


def verify():
    m = io.open(MAP_PATH, encoding="utf-8").read()
    p = io.open(PLAN_PATH, encoding="utf-8").read()
    ok = True
    for needle in ("بعد س221", "0.275.0+75", "| س221 | 2026-11-25 |",
                   "المؤجل بقرار المالك الحرفي الموثق"):
        if needle not in m:
            print(f"خريطة الحالة: مفقود {needle!r}")
            ok = False
    for needle in ("## 61.", "s221_transfer_version.py", "0.275.0+75"):
        if needle not in p:
            print(f"خطة الإصدار: مفقود {needle!r}")
            ok = False
    print("CLEAN" if ok else "FAIL")


if __name__ == "__main__":
    patch_map()
    patch_plan()
    verify()
