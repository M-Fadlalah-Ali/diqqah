    p = io.open(PLAN_PATH, encoding="utf-8").read()
    ok = True
    for needle in ("بعد س224", "| س224 | 2026-11-25 |", "التشغيل 76",
                   "0.276.0+76", "verify_b76_markers.py", "9f7b0651…e0dfc1",
                   "افتح المتابعات"):
        if needle not in m:
            print(f"خريطة الحالة: مفقود {needle!r}")
            ok = False
    for needle in ("## 64.", "45611361125", "0.276.0+76",
                   "verify_b76_markers.py", "classes.dex",
                   "build_merged_docs.py"):
        if needle not in p:
            print(f"خطة الإصدار: مفقود {needle!r}")
            ok = False
    print("CLEAN" if ok else "FAIL")


