def read(path):
    with io.open(path, "r", encoding="utf-8") as f:
        return f.read().split("\n")


def write(path, lines):
    with io.open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def replace_line(lines, startswith, must_contain, new_line, where):
    idx = [i for i, l in enumerate(lines)
           if l.startswith(startswith) and must_contain in l]
    if len(idx) != 1:
        sys.exit(f"ERR: مرساة واحدة متوقعة ب{where}: {len(idx)}")
    lines[idx[0]] = new_line
    return idx[0]


