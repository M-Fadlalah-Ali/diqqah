/// رموز عرض العملات (س50/6 — دفعة 17، بلفظ المالك: «بالأساسية تُستبدل
/// برمز العملة — ل.س تُكتب مباشرة أو $»).
///
/// المبدأ: اللفظ «بالأساسية» لغة تخزين لا لغة قسيمة — الزبون يقرأ
/// المبلغ بعملته فالرمز بجواره لا شرح تقني بعده. الرمز من جدول
/// العملات (الرمز العالمي) لا لفظ ثابت: SYP ل.س وUSD $، وأي كود آخر
/// يعود كما هو حرفاً — فلا اختلاق لرمز لم يعتمده المالك، والقيمة
/// المخزنة بلا مساس عرضاً حصراً (س-158/D-156).
///
/// س146/D-209: خريطة الكتالوج ISO 4217 المضمّن باتت مصدر الرمز لكل
/// عملة ناطقة — وخريطة التجاوز اليدوية أعلى منها باقية (SYP ل.س وUSD
/// $ بلفظ المالك المثبت م1)، والغريب عن الكتالوج والتجاوز معاً بكوده
/// حرفاً (فلا فارغ يعرض عمهماً) — دالة نقية تختبر بلا قاعدة ولا قنوات.
library;

import 'package:diqqah_domain/diqqah_domain.dart' show isoCurrencyByCode;

/// خريطة التجاوز المعتمدة — كود العملة إلى رمزها المعروض بالقسائم
/// والشاشات. م1 عملتان زرعتاهما منذ اليوم الأول (SYP/USD — D-070)
/// بأرمزتهما المعتمدة لفظاً من المالك، وأي عملة كتالوجية خلفهما
/// برمز الكتالوج (س146/D-209).
const Map<String, String> _kCurrencySymbols = {
  'SYP': 'ل.س',
  'USD': r'$',
};

/// رمز عرض العملة من كودها — التجاوز أولاً ثم الكتالوج المضمّن ثم
/// الكود حرفاً — دالة نقية تختبر بلا قاعدة ولا قنوات.
String currencySymbol(String? code) {
  if (code == null || code.trim().isEmpty) return '';
  final key = code.trim().toUpperCase();
  final override = _kCurrencySymbols[key];
  if (override != null) return override;
  final entry = isoCurrencyByCode(key);
  if (entry != null && entry.symbol.isNotEmpty) return entry.symbol;
  return key;
}

/// رمز عملة الأساس للشاشات التي لا تقرأ جدول العملات (معاينة رصيد
/// الصندوق بنماذج الإدخال) — م1 أساسية واحدة مزروعة SYP (D-070/F-120)
/// فالرمز ثابت، وتفعيل العملات المتعددة (م3) يقرؤها من جدولها.
const String kBaseCurrencySymbol = 'ل.س';
