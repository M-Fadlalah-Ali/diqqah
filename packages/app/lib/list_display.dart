import 'package:flutter/material.dart';

/// س221 — إعادة تشكيل قوائم المستندات (أمر المالك «ابدأ بتنفيذ الدفعات
/// الخمسة بالتسلسل الذي عرضته» — والمساحة الموثقة 09: «صفحات/حدود عرض»):
/// حد عرض متدرج موحد للقوائم الوثائقية — القائمة محمّلة كاملة أصلاً
/// (لا مساس بالاستعلام حرفاً ولا بنتائجه) والحد بناءُ واجهة حصراً:
/// أول شحنة [kListDisplayPageSize] صفّاً ثم زر «عرض المزيد» يوسّع
/// بشحنة تلو شحنة، فالقاعدة العامة الكبيرة لا تبني آلاف البطاقات
/// دفعة واحدة (ثقل تمرير وذاكرة) والعذر الصادق: الوجود كله متاح
/// بالتوسع المتكرر، والطباعة والتصدير بعقد F-166 على العرض المطبَّق
/// كاملاً كما كانت — الحد للشاشة لا للورقة.
///
/// نمط التطبيق: أرشيف الفواتير أولاه الدفعة (أكبر القوائم وأكثرها
/// دوالاً وبفلتر الجهة س202)، وباقي قوائم المستندات (السندات
/// والطلبات ومستندات المخزون والكشوف) تتبنى النمط ذاته بدفعة تالية
/// بأمر المالك — النمط واحد والسلوك واحد فلا تشتت.
const int kListDisplayPageSize = 60;

/// س221 — شحنة العرض الحالية: شريحة البيانات المحمّلة المسموح ببنائها
/// — النقي القابل للاختبار بعقد الشريحة (كل القائمة تحت الحد تُعاد
/// حرفاً وفوق الحد أول [limit] صفّاً حصراً).
List<T> listDisplayPage<T>(List<T> items, {required int limit}) =>
    items.length <= limit ? items : items.sublist(0, limit);

/// زر التوسيع الموحد — لسان العدّاد الباقي والدور الثانوي للثيم
/// (أدوار الثيم لا خام بعرف م05) والفعل يوسّع بشحنة واحدة.
Widget listDisplayExpandButton({
  required BuildContext context,
  required int remaining,
  required VoidCallback onExpand,
}) {
  return Padding(
    padding: const EdgeInsets.symmetric(vertical: 8),
    child: Center(
      child: OutlinedButton.icon(
        onPressed: onExpand,
        icon: const Icon(Icons.expand_more),
        label: Text('عرض المزيد — الباقي $remaining'),
      ),
    ),
  );
}
