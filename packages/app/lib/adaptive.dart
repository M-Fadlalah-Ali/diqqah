/// **والمرجع**: تركيب لوحات Filament القياسي (ترويسة صفحة وبطاقات
/// إحصاء وأدوات سريعة ومحتوى وتنبيهات وتذييل) — واستئناس AureusERP
/// غير ملزم بعرف س182 الموثق.

/// سلم المسافات — بنود 4/8 (بنود القانون أعلاه).
const double kDiqqahSpacingXs = 4;
const double kDiqqahSpacingS = 8;
const double kDiqqahSpacingM = 12;
const double kDiqqahSpacingL = 16;
const double kDiqqahSpacingXl = 24;

/// أعمدة شبكة بطاقات الوحدات على العريض — أربعة أعمدة داخل الحاوية
/// القصوى 800 بعد هوامشها الأساسية (الضيّق بلاطاته القائمة حصراً).
const int kDiqqahModuleGridColumns = 4;

/// العرض الأقصى للمحتوى الموسَّط — 800 وحدة منطقية: عرضُ سطح اختبار
/// Flutter الافتراضي ذاته فتصل البدائل بالتطبيق في الاختبار صفراً
/// (بلا مساس بأي موضع مختبر) والعريض فوقه يتوسّط.
const double kDiqqahAdaptiveMaxWidth = 800.0;

/// الهامش الأساسي على الضيّق — هوامش الشاشات القائمة ذاتها.
const double kDiqqahAdaptiveBaseMargin = 12.0;

/// الهامش الأفقي التكيفي لموضع ما — على العريض يتوسّط المحتوى
/// بعرضه الأقصى فالهامش نصف الفائض، وعلى الضيّق الهامش الأساسي
/// كما كان حرفاً (العنوان فوق العرض لا فوق البنية).
double diqqahAdaptiveHorizontalMargin(
  BuildContext context, {
  double maxWidth = kDiqqahAdaptiveMaxWidth,
  double baseMargin = kDiqqahAdaptiveBaseMargin,
}) {
  final width = MediaQuery.sizeOf(context).width;
  if (width <= maxWidth) return baseMargin;
  return (width - maxWidth) / 2;
}

/// توسيط المحتوى التكيفي — شطر العريض فوق الحد يتوسّط بعرضه الأقصى
/// والضيّق يمرر الابن كما هو بلا غلاف إضافي (لا تمديد ولا شريط).
class DiqqahAdaptiveCenter extends StatelessWidget {
  final double maxWidth;
  final Widget child;

  const DiqqahAdaptiveCenter({
    super.key,
    this.maxWidth = kDiqqahAdaptiveMaxWidth,
    required this.child,
  });

  @override
  Widget build(BuildContext context) {
    final width = MediaQuery.sizeOf(context).width;
    if (width <= maxWidth) return child;
    return Center(
      child: ConstrainedBox(
        constraints: BoxConstraints(maxWidth: maxWidth),
        child: child,
      ),
    );
  }
}
