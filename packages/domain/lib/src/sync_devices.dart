library;

/// الشركة الافتراضية الواحدة (F-111/D-188) — قيمة عمود الأحداث
/// الافتراضية (v31) وقيمة ترويسة الحزمة للتردد الواحد، ASCII خالص
/// فيمر بأمان بالترميزين وباسم الملف.
const String kDefaultCompanyId = 'main';

/// صيغة البادئة: «ج» متبوعة برقم 1..999 بلا صفر بادئ — عربيّة اللسان
/// بنموذج 08 §4 (2026/ج1/000001) ومحصورة الطول فلا رقم يتضخم على
/// القسيمة، والترقيم من 1 لا من صفر.
final RegExp _devicePrefixPattern = RegExp(r'^ج[1-9]\d{0,2}$');

/// هل النص بادئة جهاز سليمة؟
bool isValidDevicePrefix(String prefix) =>
    _devicePrefixPattern.hasMatch(prefix);

/// يصرّف البادئة أو يرمي صوتياً — حارس الشكل قبل دخولها رقماً.
String validateDevicePrefix(String prefix) {
  if (!isValidDevicePrefix(prefix)) {
    throw FormatException('بادئة جهاز غير سليمة: "$prefix" — '
        'الصيغة «ج» متبوعة برقم 1..999');
  }
  return prefix;
}

/// بادئة الجهاز الجديد بس-24 (التفريغ الأولي): أول رقم حر متصل من 1
/// على ما مأخوذ — حتمية قابلة للاختبار بلا عشوائية، والصور الفاسدة
/// بالمأخوذ تُرفض صوتياً فلا تسجيل خاطئ يمنح بادئة مكررة أبداً.
String nextDevicePrefix(Set<String> takenPrefixes) {
  for (final t in takenPrefixes) {
    validateDevicePrefix(t);
  }
  for (var n = 1; n <= 999; n++) {
    final candidate = 'ج$n';
    if (!takenPrefixes.contains(candidate)) {
      return candidate;
    }
  }
  throw StateError('نُفدت البادئات (ج1..ج999) — 999 جهازاً حداً موثقاً');
}
