///
/// **الحكم الموثق**: الترقيم محلي لكل جهاز (مفتاحه kind/year بعداد
/// متصل داخل الجهاز — F-054) والبادئة تُعرض في الرقم لا في العدّاد،
/// فجهازان ببادئتين مختلفتين يترحّلان بلا تصادم ممكن حرفاً —
/// والجهاز الواحد بلا بادئة يعيد الصيغة القائمة حرفاً (08 §4: جهاز
/// واحد يعمل بالمدى الأولى كاملة محلياً). التفريغ الأولي س-24 يعطي
/// الجاهز الجديد بادئته الحرّة التالية — والعزل بالشركة على عقد
/// الحزمة (§10) وعمود الأحداث (v31) يمتد للخادم مع أول مهايئ (د4).
///
/// **نقية حصراً** (F-010) — ولا إدارة شركات نشطة هنا: F-112/F-113
/// (الإنشاء والمبدّل والصلاحيات لكل شركة) بموضعها الموثق دفعتها
