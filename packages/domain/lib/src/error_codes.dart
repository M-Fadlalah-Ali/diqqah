/// البحث بالرمز حرفاً — مدخل السجل أو null إن لم يوجد.
DiqqahErrorCode? diqqahErrorCodeOf(String code) {
  for (final entry in diqqahErrorCodes) {
    if (entry.code == code) return entry;
  }
  return null;
}

/// خريطة استثناءات المجال النقي إلى رموزها — الترقيم عند العرض.
///
/// (خريطة استثناءات التخزين عند التخزين ذاتها — فالمجال لا يعرف شيئاً
/// عن حزم تحت مجاله بعرف F-010).
String? dqCodeForDomainError(Object error) {
  if (error is InvoiceValidationException) return 'DQ-1001';
  if (error is VoucherValidationException) return 'DQ-1002';
  if (error is CashTransferValidationException) return 'DQ-1003';
  if (error is CashAdjustmentValidationException) return 'DQ-1004';
  if (error is NegativeBalanceException) return 'DQ-1005';
  if (error is PeriodClosingException) return 'DQ-1006';
  if (error is YearCloseException) return 'DQ-1007';
  if (error is BundleValidationException) return 'DQ-1008';
  if (error is AssemblyValidationException) return 'DQ-1009';
  if (error is StockCountValidationException) return 'DQ-1010';
  if (error is StockDocValidationException) return 'DQ-1011';
  if (error is StockTransferValidationException) return 'DQ-1012';
  if (error is ReportValidationException) return 'DQ-1013';
  if (error is BackupCipherException) return 'DQ-1014';
  if (error is ItemImageException) return 'DQ-1015';
  if (error is OrderValidationException) return 'DQ-1016';
  if (error is SyncBundleEnvelopeException) return 'DQ-1109';
  if (error is SyncBundleTamperException) return 'DQ-1110';
  if (error is SyncBundleStructureException) return 'DQ-1111';
  if (error is SyncForeignCompanyException) return 'DQ-1112';
  if (error is SyncFilePartsException) return 'DQ-1115';
  if (error is JoinCodeException) return 'DQ-1116';
  if (error is SyncDeviceRevokedException) return 'DQ-1117';
  if (error is CloudArchivePayloadException) return 'DQ-1118';
  if (error is SyncAdapterException) {
    return error.serverRefused ? 'DQ-1114' : 'DQ-1113';
  }
  return null;
}
