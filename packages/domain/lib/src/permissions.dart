/// معاً بعرف بوابة الفواتير س101: ليس من الأدوار البيعية بلا اعتماد،
/// ويمتلك وحدة السندات (المدير والمحاسب افتراضاً؛ وأمين المستودع إن
/// مُنح وحدة السندات من شاشة الصلاحيات — نمط D-049). والمانح لا
/// يعتمد تحصيلَه هو — حارسُه بالجلسة والواجهة بهوية التقديم (نمط
/// س101 ذاته).
bool roleCanApproveHeldReceipts(String roleName, RolePermissions permissions) {
  if (salesSideNoApprovalRoleNames.contains(roleName.trim())) return false;
  return permissions.allows('vouchers');
}

