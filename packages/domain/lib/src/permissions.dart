///
/// النموذج مقصود البساطة على مبدأ 07 §0 (لا أنظمة وحدات عامة): الصلاحية
/// على مستوى الوحدة (بند الشاشة الهيكلية) حصراً — قائمة مفاتيح مفصولة
/// بفواصل تُخزَّن على صف الدور، أو النجمة `*` بمعنى «كل الوحدات» وهي
/// حالة دور المدير الافتراضية. لا شجرات أذونات ولا قواعد حقل-بحقل —
/// كل توسعة لاحقة قرار معروض على المالك.
///
/// الفرض بيد الواجهة: الشاشة الهيكلية تُظهر للدور وحداته المفتوحة
/// فقط، ومعطلات الهيكلية تظهر للجميع كما هي (إظهار الواقع F-016).
library;

/// مفاتيح وحدات الشاشة الهيكلية بترتيب 01 §5 — ومعها مدخل «السندات»
/// المضاف بقرار معروض (D-098): ليس بنداً في جدول النطاق لكنه بوابة
/// مستندات القبض والصرف والتحويل والتسوية وكان مدخله السابق زراً مدفوناً
/// بشاشة الصناديق فلم يلمحه المالك (س37) — فصار بنداً رئيسياً.
const List<String> moduleKeys = <String>[
  'parties', // الأطراف
  'items', // الأصناف
  'units', // وحدات القياس والتعبئة
  'warehouses', // المستودعات
  'invoices', // الفواتير
  'vouchers', // السندات (D-098 معروض)
  'orders', // طلبات الشراء والبيع
  'receivables', // الذمم
  'boxes', // الصناديق
