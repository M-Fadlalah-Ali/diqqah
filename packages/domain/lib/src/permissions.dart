  'currencies', // العملات
  'roles', // الصلاحيات
  'reports', // التقارير اليومية
  'sync', // المزامنة
  'settings', // الإعدادات
];

/// التسمية العربية لكل مفتاح وحدة — العرض في شاشة الصلاحيات والمطبوعات.
const Map<String, String> moduleLabels = <String, String>{
  'parties': 'الأطراف',
  'items': 'الأصناف',
  'units': 'وحدات القياس والتعبئة',
  'warehouses': 'المستودعات',
  'invoices': 'الفواتير',
  'vouchers': 'السندات',
  'orders': 'طلبات الشراء والبيع',
  'receivables': 'الذمم',
  'boxes': 'الصناديق',
  'ledger': 'الدفتر المحاسبي',
  'currencies': 'العملات',
  'roles': 'الصلاحيات',
  'reports': 'التقارير اليومية',
  'sync': 'المزامنة',
  'settings': 'الإعدادات',
};

/// قيمة التخزين التي تعني «كل الوحدات بلا استثناء» — دور المدير.
const String allModulesToken = '*';

/// نموذج صلاحيات دور واحد — محلل ومصوغ مكتوب، والقراءة النقية تختبر.
class RolePermissions {
  /// الصيغة المخزنة على صف الدور: `*` أو قائمة مفاتيح بفواصل.
  final String stored;

  const RolePermissions(this.stored);

  /// دور بكل الوحدات — المدير الافتراضي.
  const RolePermissions.all() : stored = allModulesToken;

  /// المفاتيح المصرَّح بها فعلاً (الموجودة في القائمة المعروفة حصراً —
  /// المفتاح المجهول يُسقط صامتاً كي لا تتيح بقايا قديمة وحدة لم تعتمد).
  List<String> get keys => stored == allModulesToken
      ? List<String>.unmodifiable(moduleKeys)
      : List<String>.unmodifiable(<String>[
          for (final raw in stored.split(','))
            if (moduleKeys.contains(raw.trim())) raw.trim(),
        ]);

  /// هل يمتلك الدور الوحدة؟ المدير (`*`) يمتلك كل شيء.
  bool allows(String moduleKey) =>
      stored == allModulesToken || keys.contains(moduleKey);

  /// هل الدور كامل الوحدات (نجمة)؟ — لتلوين العرض في شاشة الصلاحيات.
  bool get isAll => stored == allModulesToken;

  /// صياغة التخزين من مفاتيح مختارة — بترتيب القائمة المعروفة حصراً
  /// وبإسقاط التكرار والمجهول، والقائمة الفارغة صيغة صالحة (دور بلا
  /// وحدات ظاهرة — يرى الرئيسية المعطلة وحدها).
  static String format(Iterable<String> selected) {
    final chosen = selected.toSet();
    return <String>[
      for (final key in moduleKeys)
        if (chosen.contains(key)) key,
    ].join(',');
  }

  /// ملخص عربي للعرض: «كل الوحدات» أو أسماء الوحدات مفصولة بـ«، ».
  String get summary => isAll
      ? 'كل الوحدات'
      : keys.isEmpty
          ? 'لا وحدات'
          : keys.map((k) => moduleLabels[k] ?? k).join('، ');
}

/// الأدوار النمطية الأربعة الجاهزة بأذوناتها الافتراضية (F-080،
/// D-100 معروض) — يزرعها التخزين آلياً عند الترحيلة v10 ولأول تشغيل،
/// ويبقى تعديل الأذونات بعدها بيد المالك من شاشة الصلاحيات.
///
/// منطق الأذونات الافتراضية بلغة المحل:
/// - «مدير»: كل شيء — المسؤول الأول.
/// - «محاسب»: المحاسبة كلها (القيد والسند والصندوق والتقارير والدفتر
///   والإعدادات) بلا الصلاحيات ولا المزامنة.
/// - «أمين مستودع»: الأصناف والتقارير اليومية (المخزون والحركة) —
///   بلا نقود باتاً (لا فواتير ولا سندات ولا صناديق).
/// - «بائع»: الأطراف والفواتير والسندات (يبيع ويقبض) — بلا التقارير
///   ولا الإعدادات ولا الصلاحيات.
