/// فحص الثوابت الآلي (F-006، 07 §1.10، D-067) — أنواع التقرير النقية.
///
/// معيار جاهزية م1-نواة الموثق (09 §2): «فحص الثوابت (الأربعة +
/// المطابقة الثلاثة D-067) يعمل آلياً». الثوابت الأربعة من 07 §1.10
/// والمطابقة الثلاثة من إضافة جولة المراجعة (D-067) — وسبعة فحوص
/// قراءةً خالصة لا تكتب شيئاً: الفحص لا يعالج الخرق، يكشفه ويوقف
/// الثقة فيه (أي خرق ثابت = تنبيه فوري — 07 §1.10).
///
/// موضعا الفحص الموثقان (D-067): الفحص الموضعي داخل معاملة الترحيل
/// على المتأثرات (منفذ بمُشغِّلات الحواجز والمدقق)، والفحص الكامل
/// بالخلفية عند الخمول أو بيد المالك — وهذا التقرير هو الفحص الكامل
/// بيد المالك (بطاقة الإعدادات) والافتتاحي الصامت (رئيسية التطبيق).
library;

/// ثوابت الفحوص السبعة وأسماؤها العربية الموثقة — الفحص يُرفد برمزها
/// والعرض ببطاقات النتائج.
const Map<String, String> integrityCheckLabels = <String, String>{
  'T1': 'توازن القيود المرحّلة (07 §1.1)',
  'T2': 'عدم سالبية المخزون (F-042)',
  'T3': 'كل حركة صندوق بمستند مرحّل — لا حركة يتيمة (N-009)',
  'T4': 'كل فاتورة مرحّلة لها قيد مرتبط (07 §1.10)',
  'M1': 'مطابقة حسابات الصناديق 111x مع أرصدة الصناديق (D-067)',
  'M2': 'مطابقة حساب المخزون 113 مع قيمة المخزون (D-067)',
  'M3': 'مطابقة حسابَي الذمم 112/211 مع أرصدة الأطراف (D-067)',
};

/// خرق ثابت واحد — رمز الفحص ووصفه العربي وما وجد.
class IntegrityViolation {
  /// رمز الفحص المخترق (من [integrityCheckLabels]).
  final String checkCode;

  /// وصف الخرق العربي — محمول بيانات (رقم المستند والقيم) لا نص جاهز،
  /// على نمط مدققات المجال المعتمدة.
  final String detail;

  const IntegrityViolation({required this.checkCode, required this.detail});

  @override
  String toString() => '${integrityCheckLabels[checkCode] ?? checkCode}: $detail';
}

/// تقرير الفحص الكامل للثوابت السبعة — خروقات متعددة ممكنة بجولة واحدة
/// والنظيف معناها صفر خروقات لا «فحوص لم تنفذ».
class IntegrityReport {
  final List<IntegrityViolation> violations;

  const IntegrityReport(this.violations);

  /// نظيف؟ — صفر خروقات على السبعة كلها.
  bool get isClean => violations.isEmpty;

  /// عدد الفحوص المنفذة دائماً سبعة — لعرض «سليمة 7/7».
  static const int totalChecks = 7;

  /// سطر الخلاصة العربي للعرض المباشر.
  String get summary => isClean
      ? 'الفحوص السبعة سليمة (7/7)'
      : 'خروق: ${violations.length} — راجع التفصيل أدناه';
}
