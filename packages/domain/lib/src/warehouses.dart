/// وحدة المستودعات — الفحوص الخالصة للإدارة (المرحلة 2، دفعة 24).
///
/// القاعدة: أسماء المستودعات فريدة (قاعدة القيد UNIQUE في 05 §3.3) —
/// الفحص الخالص هنا (فراغ وحد أقصى) وقاعدة التفرد بيد التخزين على ما
/// خُزّن (نمط الفواتير: المدقق البنيوي بالمجال والفحوص المحركية هناك).
/// بلا حذف أبداً — المرجع المحاسبي المرتبط بحركات لا يُحذف؛ التعطيل
/// وحده والحراسة على الرصيد وآخر نشط بيد التخزين.
library;

/// حد الاسم — بما يسع خانة شاشة دون كسر (قرار عرض لا قاعدة محاسبية).
const int warehouseNameMaxLength = 60;

/// خطأ اسم المستودع أو null إن كان صالحاً.
String? warehouseNameError(String name) {
  final trimmed = name.trim();
  if (trimmed.isEmpty) return 'اسم المستودع إلزامي';
  if (trimmed.length > warehouseNameMaxLength) {
    return 'اسم المستودع أطول من $warehouseNameMaxLength حرفاً — '
        'اختصر الاسم';
  }
  return null;
}
